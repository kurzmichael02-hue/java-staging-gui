package de.logicalis.java_staging_gui;

import java.util.Locale;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

@Component
public class ConfigGenerator {

    @Value("${cisco.admin.password}")
    private String adminPassword;

    @Value("${cisco.snmp.community:public}")
    private String snmpCommunity;

    public String generate(Device device) {
        String profile = device.getConfigProfile();
        if (profile == null) profile = "S";

        switch (profile.toUpperCase(Locale.ROOT)) {
            case "M":  return generateM(device);
            case "L":  return generateL(device);
            default:   return generateS(device);
        }
    }

    private String mask(Device device) {
        String m = device.getSubnetMask();
        return (m != null && !m.isEmpty()) ? m : "255.255.255.0";
    }

    // only write gateway/dns when they are set - otherwise the literal "null" would end
    // up in the config (string concatenation of null). the fields are already checked for
    // IPv4 in step 3, this is just the second line of defense.
    private void appendGatewayDns(StringBuilder sb, Device device) {
        if (notEmpty(device.getDefaultGatewayIp()))
            sb.append("ip default-gateway ").append(device.getDefaultGatewayIp()).append("\n");
        if (notEmpty(device.getLocalDnsServerIp()))
            sb.append("ip name-server ").append(device.getLocalDnsServerIp()).append("\n");
        sb.append("!\n");
    }

    private static boolean notEmpty(String s) {
        return s != null && !s.isEmpty();
    }

    // user input (hostname/serial/location) ends up raw in the config and in the
    // banner - line breaks/^C could otherwise smuggle in extra IOS commands.
    private static String clean(String s) {
        if (s == null) return "";
        return s.replace("\r", "").replace("\n", " ").replace("^", "");
    }

    // crypto key generate rsa is not emitted here, it is an
    // interactive command and has to run directly on the switch
    private String sshBase(Device device) {
        StringBuilder sb = new StringBuilder();
        sb.append("ip domain-name example.local\n");
        sb.append("ip ssh version 2\n");
        sb.append("ip ssh time-out 60\n");
        sb.append("ip ssh authentication-retries 3\n");
        sb.append("!\n");
        sb.append("username admin privilege 15 secret ").append(adminPassword).append("\n");
        sb.append("!\n");
        sb.append("line vty 0 4\n");
        sb.append(" login local\n");
        sb.append(" transport input ssh\n");
        sb.append(" exec-timeout 10 0\n");
        sb.append("!\n");
        sb.append("line con 0\n");
        sb.append(" exec-timeout 10 0\n");
        sb.append("!\n");
        return sb.toString();
    }

    private String generateS(Device device) {
        StringBuilder sb = new StringBuilder();

        sb.append("! ============================================================\n");
        sb.append("! Profile Lite\n");
        sb.append("! Generated by Staging GUI\n");
        sb.append("! Hostname : ").append(clean(device.getHostname())).append("\n");
        sb.append("! Serial   : ").append(clean(device.getSerialNumber())).append("\n");
        sb.append("! ============================================================\n");
        sb.append("!\n");

        sb.append("hostname ").append(clean(device.getHostname())).append("\n");
        sb.append("!\n");

        sb.append("interface vlan 1\n");
        sb.append(" ip address ").append(device.getIp()).append(" ").append(mask(device)).append("\n");
        sb.append(" no shutdown\n");
        sb.append("!\n");

        appendGatewayDns(sb, device);

        sb.append(sshBase(device));

        sb.append("end\n");
        return sb.toString();
    }

    private String generateM(Device device) {
        StringBuilder sb = new StringBuilder();

        sb.append("! ============================================================\n");
        sb.append("! Profile Standard\n");
        sb.append("! Generated by Staging GUI\n");
        sb.append("! Hostname : ").append(clean(device.getHostname())).append("\n");
        sb.append("! Serial   : ").append(clean(device.getSerialNumber())).append("\n");
        sb.append("! ============================================================\n");
        sb.append("!\n");

        sb.append("hostname ").append(clean(device.getHostname())).append("\n");
        sb.append("!\n");

        sb.append("interface vlan 1\n");
        sb.append(" ip address ").append(device.getIp()).append(" ").append(mask(device)).append("\n");
        sb.append(" no shutdown\n");
        sb.append("!\n");

        appendGatewayDns(sb, device);

        sb.append(sshBase(device));

        if (notEmpty(device.getUpstreamSwitch()) && device.getUpstreamPort() > 0) {
            sb.append("interface GigabitEthernet1/0/").append(device.getUpstreamPort()).append("\n");
            sb.append(" description UPLINK-TO-").append(clean(device.getUpstreamSwitch()).toUpperCase(Locale.ROOT)).append("\n");
            sb.append(" switchport mode trunk\n");
            sb.append(" spanning-tree portfast trunk\n");
            sb.append(" no shutdown\n");
            sb.append("!\n");
        }

        sb.append("end\n");
        return sb.toString();
    }

    private String generateL(Device device) {
        StringBuilder sb = new StringBuilder();

        sb.append("! ============================================================\n");
        sb.append("! Profile Extended\n");
        sb.append("! Generated by Staging GUI\n");
        sb.append("! Hostname : ").append(clean(device.getHostname())).append("\n");
        sb.append("! Serial   : ").append(clean(device.getSerialNumber())).append("\n");
        sb.append("! ============================================================\n");
        sb.append("!\n");

        sb.append("hostname ").append(clean(device.getHostname())).append("\n");
        sb.append("!\n");

        // aaa must come before ssh, otherwise login authentication below has nothing to bind to
        sb.append("aaa new-model\n");
        sb.append("aaa authentication login default local\n");
        sb.append("aaa authorization exec default local if-authenticated\n");
        sb.append("!\n");

        sb.append("interface vlan 1\n");
        sb.append(" ip address ").append(device.getIp()).append(" ").append(mask(device)).append("\n");
        sb.append(" no shutdown\n");
        sb.append("!\n");

        appendGatewayDns(sb, device);

        // line vty below uses 'login authentication default' instead of 'login local',
        // because the aaa model is active
        sb.append("ip domain-name example.local\n");
        sb.append("ip ssh version 2\n");
        sb.append("ip ssh time-out 60\n");
        sb.append("ip ssh authentication-retries 3\n");
        sb.append("!\n");
        sb.append("username admin privilege 15 secret ").append(adminPassword).append("\n");
        sb.append("!\n");
        sb.append("line vty 0 4\n");
        sb.append(" login authentication default\n");
        sb.append(" transport input ssh\n");
        sb.append(" exec-timeout 10 0\n");
        sb.append("!\n");
        sb.append("line con 0\n");
        sb.append(" exec-timeout 10 0\n");
        sb.append("!\n");

        if (notEmpty(device.getUpstreamSwitch()) && device.getUpstreamPort() > 0) {
            sb.append("interface GigabitEthernet1/0/").append(device.getUpstreamPort()).append("\n");
            sb.append(" description UPLINK-TO-").append(clean(device.getUpstreamSwitch()).toUpperCase(Locale.ROOT)).append("\n");
            sb.append(" switchport mode trunk\n");
            sb.append(" spanning-tree portfast trunk\n");
            sb.append(" no shutdown\n");
            sb.append("!\n");
        }

        if (notEmpty(device.getNtpServer())) {
            sb.append("ntp server ").append(clean(device.getNtpServer())).append("\n");
            sb.append("!\n");
        }

        sb.append("ip dhcp snooping\n");
        sb.append("ip dhcp snooping vlan 1\n");
        sb.append("no ip dhcp snooping information option\n");
        sb.append("!\n");

        if (notEmpty(device.getLocalPrtgSensorIp())) {
            sb.append("logging host ").append(device.getLocalPrtgSensorIp()).append("\n");
            sb.append("logging trap informational\n");
            sb.append("!\n");
        }

        sb.append("snmp-server community ").append(snmpCommunity).append(" RO\n");
        sb.append("snmp-server location ").append(clean(device.getLocationName())).append("\n");
        sb.append("snmp-server contact netops@example.com\n");
        sb.append("!\n");

        sb.append("banner motd ^C\n");
        sb.append("***TEST-LOGICALIS***\n");
        sb.append("Unauthorized access is prohibited.\n");
        sb.append("Device  : ").append(clean(device.getHostname())).append("\n");
        sb.append("Serial  : ").append(clean(device.getSerialNumber())).append("\n");
        sb.append("Location: ").append(clean(device.getLocationName())).append("\n");
        sb.append("^C\n");
        sb.append("!\n");

        sb.append("end\n");
        return sb.toString();
    }
}
